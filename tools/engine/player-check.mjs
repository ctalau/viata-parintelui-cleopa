import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
const urls = [];
page.on('request', (r) => urls.push(r.url()));
page.on('pageerror', (e) => console.log('pageerror', e.message));
page.on('console', (m) => m.type() === 'error' && console.log('console', m.text()));
await page.goto('http://127.0.0.1:4173/episoade/painea-care-poate-sa-astepte/');
await page.waitForFunction(() => document.querySelector('#episode-picture')?.dataset.frame, null, { timeout: 120000 });
console.log('primul cadru', await page.$eval('#episode-picture', (c) => c.dataset.frame));
await page.evaluate(() => { const a = document.querySelector('#episode'); a.currentTime = 60; });
await page.waitForFunction(() => Number(document.querySelector('#episode-picture').dataset.frame) > 1400, null, { timeout: 60000 });
console.log('după salt', await page.$eval('#episode-picture', (c) => c.dataset.frame));
await page.click('#play').catch(() => {});
await page.waitForTimeout(3000);
console.log('după redare', await page.$eval('#episode-picture', (c) => c.dataset.frame), await page.$eval('#episode', (a) => a.currentTime.toFixed(2)));
await page.screenshot({ path: '/tmp/claude-0/-home-user-viata-parintelui-cleopa/364ac521-c588-5348-b214-23d9365e1fdd/scratchpad/player.png' });
console.log('plan-* cerute:', urls.filter((u) => /plan-\d+\.(bin|json)/.test(u)).length, '· GLB:', urls.filter((u) => u.endsWith('.glb')).length);
await browser.close();
