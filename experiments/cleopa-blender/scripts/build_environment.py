    a.diamond(x,y,.049*s,.057*s,'ffe4b7')
    a.diamond(x,y,.022*s,.030*s,dark)
    for sign in (-1,1):
        a.diamond(x+.148*s*sign,y,.029*s,.041*s,dark)
        a.diamond(x,y+.142*s*sign,.041*s,.028*s,green)


