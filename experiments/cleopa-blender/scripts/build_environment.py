def plank(a,x0,y0,x1,y1,tone='88553a',vertical=False,seed=2):
    a.rect(x0,y0,x1,y1,tone,WOOD_INK,.045)
    rng=random.Random(seed)
    w,h=x1-x0,y1-y0
    if vertical:
        a.line([(x0+.13*w,y0+.02*h),(x0+.13*w,y1-.027*h)],'a66a47',.027)
        a.line([(x1-.16*w,y0+.03*h),(x1-.16*w,y1-.018*h)],'633d30',.026)
        for i in range(9):
            y=y0+h*rng.uniform(.04,.89);x=x0+w*rng.uniform(.25,.76);dy=h*rng.uniform(.04,.16)
            a.line(f'M {x} {y} Q {x-.09*w} {y+dy*.52} {x+.038*w} {y+dy}', '9c6242' if i%3 else '684131',.014)
    else:
        a.line([(x0+.03*w,y1-.20*h),(x1-.025*w,y1-.20*h)],'b47850',.031)
        a.line([(x0+.016*w,y0+.19*h),(x1-.035*w,y0+.19*h)],'654030',.028)
        for i in range(10):
            x=x0+w*rng.uniform(.025,.86);y=y0+h*rng.uniform(.26,.75);dx=w*rng.uniform(.035,.12)
            a.line(f'M {x} {y} Q {x+dx*.5} {y+.105*h} {x+dx} {y-.015*h}', 'a9704a' if i%3 else '633e30',.018)


def textile(a,x,y,s,muted=False):
    red='ab493c' if not muted else 'b36b4c'
    dark='5c4850' if not muted else '7a6b55'
